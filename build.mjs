import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';

const helper = await readFile(new URL('./helper.py', import.meta.url), 'utf8');
const template = await readFile(new URL('./plugin.template.js', import.meta.url), 'utf8');
const sha256 = createHash('sha256').update(helper).digest('hex');
await writeFile(new URL('./plugin.js', import.meta.url), `// Generated by build.mjs from plugin.template.js and helper.py (sha256 ${sha256}). Edit those, then rebuild.\nconst HELPER_SOURCE = ${JSON.stringify(helper)};\n${template}`);
console.log(`Built Blaze Review with helper ${sha256.slice(0, 12)}.`);
